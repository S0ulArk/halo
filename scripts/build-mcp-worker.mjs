// Embeds the Claude connector Worker (src/mcp/worker/worker.js) in the app as src/mcp/workerSource.ts, with a short
// hash of its text: Halo uploads the text to the person's Cloudflare account and re-uploads when the hash changes.
// Run after editing worker.js: `node scripts/build-mcp-worker.mjs` (src/mcp/workerSource.test.ts fails until you do).
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync(new URL("../src/mcp/worker/worker.js", import.meta.url), "utf8");
const hash = createHash("sha256").update(src).digest("hex").slice(0, 12);
const out = `// Generated by scripts/build-mcp-worker.mjs from src/mcp/worker/worker.js. Do not edit.
export const WORKER_VERSION = ${JSON.stringify(hash)};
export const WORKER_SOURCE = ${JSON.stringify(src)};
`;
writeFileSync(new URL("../src/mcp/workerSource.ts", import.meta.url), out);
console.log(`workerSource.ts written (${src.length} chars, version ${hash})`);
